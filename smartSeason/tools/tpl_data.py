def build(namespace, services, pgbouncer_ini, pgbouncer_entrypoint):
    """Renders the data tier.

    `services` are catalogue entries; their `db` key is used directly rather than
    derived from the service name, because two of the twenty-seven do not match.
    """
    lines = []
    for spec in services:
        db = spec["db"]
        lines.append(
            f'    psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" '
            f"-c \"CREATE DATABASE {db};\""
        )
    init_sql = "\n".join(lines)

    def indent(text, spaces=4):
        pad = " " * spaces
        return "\n".join(pad + line if line.strip() else "" for line in text.rstrip().split("\n"))

    return DATA_LAYER.format(
        ns=namespace,
        init_sql=init_sql,
        pgbouncer_ini=indent(pgbouncer_ini),
        pgbouncer_entrypoint=indent(pgbouncer_entrypoint),
    )
