"""The data tier the 27 services depend on.

Until this existed the k8s manifests deployed the application tier alone. The
ConfigMap named `postgres.smartseason.svc.cluster.local`, `redis` and `kafka:9092`,
and nothing in the repository created any of them, so `kubectl apply -f k8s/`
produced 29 deployments that crash-looped on an unresolvable database host.

`check-k8s-env.py` could not catch it and still cannot: it verifies that every
variable is *provided* and that every Secret and ConfigMap key *exists*. Whether the
hostname in a value is backed by a running workload is a different question, and a
green gate answered the first one convincingly enough to hide the second.

Three deliberate limits, stated here because they are the ceiling of this tier:

  - **One replica each.** Postgres, Redis and Redpanda are single pods. That makes
    the data layer a single point of failure and caps the whole platform's
    availability at one node's. It is honest for a first cluster deploy and must be
    replaced by managed services, or by an operator that runs real replication,
    before this carries production traffic.
  - **Object storage is MinIO, single node.** S3-compatible on purpose: swapping to real S3,
    Spaces or R2 later is a config change, not a rewrite. One replica means it is not durable
    against node loss - that is what a managed bucket is for.
  - **No read replicas**, so every read still lands on the primary. The services
    already annotate 131 transactions `readOnly = true`, so the routing hook exists;
    nothing routes yet.
  - **PgBouncer over-subscribes on purpose.** See the arithmetic in the manifest.

The PgBouncer configuration is read from `infra/docker/pgbouncer/` at generation
time rather than copied here. Two hand-maintained copies of a connection-pooler
config drift, and the failure when they do is a pool size that is correct locally
and wrong in the cluster.
"""

